/** Every locale the host ships, keyed by its BCP 47 tag. */
const dictionaries = {
  en,
  de,
  fr,
  nl,
  'zh-CN': zhCN,
  'zh-TW': zhTW,
  uk,
  es,
  'pt-BR': ptBR,
  ko,
  pl,
  ja,
  tr,
};

/**
 * Completeness and nothing else: a locale that is missing a key, or carries one
 * English does not have, fails here instead of showing an empty string later.
 */
const checked = <Tag extends string>(locales: { [Key in Tag]: Dictionary }): void => {
  void locales;
};
checked(dictionaries);

const byTag = new Map(
  Object.entries(dictionaries).map(([tag, dictionary]) => [tag.toLowerCase(), dictionary]),
);

/** Falls back to English rather than showing nothing for an unknown tag. */
export const resolveDictionary = (locale: string): Dictionary =>
  byTag.get(locale.trim().toLowerCase()) ?? en;